# Campus Health Index — five dimensions, each with its formula and inputs shown
# ---------------------------------------------------------------------------

DIMENSION_WEIGHTS = {"safety": 0.25, "response": 0.25, "infrastructure": 0.2, "maintenance": 0.15, "network": 0.15}


def compute_health(tickets: List[Dict], at: datetime, breach_overrides: Optional[set] = None,
                   resolved_overrides: Optional[set] = None) -> Dict[str, Any]:
    breach_overrides = breach_overrides or set()
    resolved_overrides = resolved_overrides or set()
    open_t = [t for t in tickets if _is_open(t, at) and t["id"] not in resolved_overrides]
    breached = [t for t in open_t if _is_breached(t, at) or t["id"] in breach_overrides]
    dims: Dict[str, Dict[str, Any]] = {}

    # Response: share of open work inside SLA, blended with on-time resolution over 30 days
    recent_closed = [t for t in tickets if t["closed_at"] and at - timedelta(days=30) <= t["closed_at"] <= at]
    on_time = [t for t in recent_closed if t["closed_at"] <= t["due"]]
    if not open_t and not recent_closed:
        dims["response"] = {"score": None, "detail": "Insufficient data — no open or recently resolved incidents."}
    else:
        within = 1 - (len(breached) / len(open_t)) if open_t else 1.0
        ontime = (len(on_time) / len(recent_closed)) if recent_closed else within
        dims["response"] = {
            "score": round(100 * (0.6 * within + 0.4 * ontime)),
            "detail": f"{len(open_t) - len(breached)}/{len(open_t)} open incidents within SLA; "
                      f"{len(on_time)}/{len(recent_closed)} resolved on time (30 days).",
            "formula": "60% × open-within-SLA ratio + 40% × on-time resolution ratio",
        }

    def load_score(items: List[Dict]) -> int:
        return max(0, 100 - sum(PRIORITY_WEIGHT.get(t["priority"], 5) for t in items))

    safety_items = [t for t in open_t if t["category"] == "Security" or t["priority"] == "Critical"]
    dims["safety"] = {
        "score": load_score(safety_items),
        "detail": f"{len(safety_items)} open safety-relevant incidents (Security category or Critical priority).",
        "formula": "100 − Σ priority weight (Critical 20, High 10, Medium 5, Low 2)",
    }
    infra_items = [t for t in open_t if t["category"] in ("Water", "Electrical", "Infrastructure")]
    dims["infrastructure"] = {
        "score": load_score(infra_items),
        "detail": f"{len(infra_items)} open water / electrical / structural incidents.",
        "formula": "100 − Σ priority weight of open infrastructure incidents",
    }
    net_items = [t for t in open_t if t["category"] == "Network"]
    dims["network"] = {
        "score": load_score(net_items),
        "detail": f"{len(net_items)} open network incidents.",
        "formula": "100 − Σ priority weight of open network incidents",
    }
    if open_t:
        unassigned = [t for t in open_t if not _is_assigned(t, at)]
        stale = [t for t in open_t if (at - min(t["last_activity"], at)) > timedelta(hours=24)]
        dims["maintenance"] = {
            "score": round(100 - 50 * len(unassigned) / len(open_t) - 50 * len(stale) / len(open_t)),
            "detail": f"{len(unassigned)} of {len(open_t)} open incidents unassigned; {len(stale)} with no activity for 24h+.",
            "formula": "100 − 50 × unassigned ratio − 50 × stale (no update 24h) ratio",
        }
    else:
        dims["maintenance"] = {"score": 100, "detail": "No open maintenance backlog.", "formula": "No backlog"}

    scored = {k: v for k, v in dims.items() if v["score"] is not None}
    wsum = sum(DIMENSION_WEIGHTS[k] for k in scored)
    overall = round(sum(v["score"] * DIMENSION_WEIGHTS[k] for k, v in scored.items()) / wsum) if wsum else None
    return {"score": overall, "dimensions": dims, "open": len(open_t), "breached": len(breached),
            "weights": DIMENSION_WEIGHTS}


def health_report(snap: Dict[str, Any]) -> Dict[str, Any]:
    tickets, now = snap["tickets"], snap["loaded_at"]
    if not tickets:
        return {"score": None, "dimensions": {}, "change": None, "message": "No operational data yet."}
    current = compute_health(tickets, now)
    past_at = now - timedelta(hours=24)
    has_history = any(t["created"] <= past_at for t in tickets)
    change = None
    if has_history:
        past = compute_health(tickets, past_at)
        new_24 = [t for t in tickets if past_at < t["created"] <= now]
        newly_breached = [t for t in tickets if past_at < t["due"] <= now and _is_open(t, t["due"])]
        resolved_24 = [t for t in tickets if t["closed_at"] and past_at < t["closed_at"] <= now]
        reasons = []
        hp = Counter(t["priority"] for t in new_24 if t["priority"] in ("Critical", "High"))
        if new_24:
            reasons.append(f"{len(new_24)} new incident{'s' if len(new_24) != 1 else ''} reported"
                           + (f" ({', '.join(f'{v} {k}' for k, v in hp.items())})" if hp else ""))
        if newly_breached:
            reasons.append(f"{len(newly_breached)} incident{'s' if len(newly_breached) != 1 else ''} crossed the SLA deadline")
        if resolved_24:
            reasons.append(f"{len(resolved_24)} incident{'s' if len(resolved_24) != 1 else ''} resolved")
        if current["open"] != past["open"]:
            reasons.append(f"open backlog {'grew' if current['open'] > past['open'] else 'shrank'} from {past['open']} to {current['open']}")
        dim_deltas = {k: (current["dimensions"][k]["score"] - past["dimensions"][k]["score"])
                      if current["dimensions"][k]["score"] is not None and past["dimensions"][k]["score"] is not None else None
                      for k in current["dimensions"]}
        change = {
            "previous": past["score"],
            "delta": (current["score"] - past["score"]) if current["score"] is not None and past["score"] is not None else None,
            "window": "24h",
            "reasons": reasons or ["No material change in the last 24 hours."],
            "dimension_deltas": dim_deltas,
            "method": "Past score reconstructed from ticket creation, SLA and resolution timestamps (current priorities used).",
        }
    return {**current, "change": change,
            "note": None if has_history else "Insufficient history to compute a 24h trend."}


