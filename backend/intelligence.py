def overview() -> Dict[str, Any]:
    snap = snapshot()
    tickets, now = snap["tickets"], snap["loaded_at"]
    signals = detect_signals(snap)
    warnings = early_warnings(snap, signals)
    open_t = [t for t in tickets if t["status"] in OPEN]
    risks = sla_risks(snap)
    by_building: Dict[str, Dict[str, Any]] = {}
    for b, cfg in BUILDINGS.items():
        items = [t for t in open_t if t["building"] == b]
        bsig = [s for s in signals if s.get("building") == b or b in buildings_on_line(s["service"], s["line"] or "")]
        by_building[b] = {"building": b, "type": cfg["type"], "zone": cfg["zone"], "open": len(items),
                          "critical": sum(1 for t in items if t["priority"] == "Critical"),
                          "breached": sum(1 for t in items if t["due"] < now),
                          "risk_level": bsig[0]["level"] if bsig else None,
                          "signal_ids": [s["id"] for s in bsig]}
    owners = Counter(t["owner"] for t in open_t if t["owner"] not in (None, "", "Unassigned"))
    since = now - timedelta(hours=24)
    changes = []
    for t in tickets:
        for l in t["logs"]:
            if l["at"] and l["at"] >= since:
                changes.append({"ticket_id": t["id"], "action": l["action"], "actor": l["actor"], "at": _iso(l["at"]), "building": t["building"]})
    changes.sort(key=lambda c: c["at"], reverse=True)
    return {
        "generated_at": now.isoformat(),
        "health": health_report(snap),
        "kpis": {
            "active": len(open_t),
            "critical": sum(1 for t in open_t if t["priority"] == "Critical"),
            "overdue": len(risks["breached"]),
            "approaching_sla": len(risks["approaching"]),
            "emerging_risks": sum(1 for w in warnings if w["state"] == "active" and w["kind"] != "sla"),
            "unassigned": sum(1 for t in open_t if t["owner"] in (None, "", "Unassigned")),
            "response_load": {"staff_engaged": len(owners), "busiest": owners.most_common(1)[0] if owners else None,
                              "avg_per_staff": round(sum(owners.values()) / len(owners), 1) if owners else 0},
        },
        "warnings": warnings,
        "signals": signals[:8],
        "sla": risks,
        "buildings": list(by_building.values()),
        "live_incidents": [_brief(t, now) for t in sorted(open_t, key=lambda t: t["created"], reverse=True)[:12]],
        "recent_changes": changes[:15],
        "graph": incident_graph(snap, signals=signals),
        "topology": TOPOLOGY_VERSION,
        "demo_ticket_ids": demo_ticket_ids(),
        "reverification": _reverification_queue(snap),
        "data_note": "All figures are computed from KAIROS tickets and audit logs; dependencies come from the configured campus topology.",
    }


def _reverification_queue(snap: Dict[str, Any]) -> Dict[str, Any]:
    awaiting, disputed, verified = [], [], 0
    for t in snap["tickets"]:
        v = verification_for(t, snap["tickets"], snap["loaded_at"])
        if v["state"] == "awaiting_reporter":
            awaiting.append({"ticket_id": t["id"], "title": t["title"], "resolved_at": v["resolved_at"], "policy": v["policy"]["level"]})
        elif v["state"] in ("disputed", "disputed_returned"):
            disputed.append({"ticket_id": t["id"], "title": t["title"], "reason": v["last_dispute"]["reason_label"], "at": v["last_dispute"]["at"], "status": t["status"]})
        elif v["state"] == "verified_reporter":
            verified += 1
    return {"awaiting": awaiting, "disputed": disputed, "verified_by_reporter": verified}


