def init_intelligence_tables() -> None:
    conn, engine = get_connection()
    cur = conn.cursor()
    pk = "SERIAL PRIMARY KEY" if engine == "postgresql" else "INTEGER PRIMARY KEY AUTOINCREMENT"
    cur.execute("""
    CREATE TABLE IF NOT EXISTS signal_states (
        signal_key TEXT PRIMARY KEY,
        state TEXT NOT NULL,
        fingerprint TEXT NOT NULL,
        actor TEXT NOT NULL,
        note TEXT,
        updated_at TEXT NOT NULL
    )""")
    cur.execute(f"""
    CREATE TABLE IF NOT EXISTS resolution_verifications (
        id {pk},
        ticket_id TEXT NOT NULL,
        method TEXT NOT NULL,
        actor TEXT NOT NULL,
        note TEXT,
        image TEXT,
        created_at TEXT NOT NULL
    )""")
    cur.execute("""
    CREATE TABLE IF NOT EXISTS reporter_credentials (
        ticket_id TEXT PRIMARY KEY,
        token_hash TEXT NOT NULL,
        created_at TEXT NOT NULL
    )""")
    conn.commit()
    try:
        cur.execute("ALTER TABLE resolution_verifications ADD COLUMN reason TEXT")
        conn.commit()
    except Exception:
        conn.rollback()  # column already exists
    conn.close()


def invalidate() -> None:
    with _lock:
        _cache["snap"] = None


def _now() -> datetime:
    return datetime.now(timezone.utc)


def _parse(ts: Any) -> Optional[datetime]:
    if not ts:
        return None
    try:
        dt = datetime.fromisoformat(str(ts).replace("Z", "+00:00"))
        return dt if dt.tzinfo else dt.replace(tzinfo=timezone.utc)
    except (ValueError, TypeError):
        return None


def _iso(dt: Optional[datetime]) -> Optional[str]:
    return dt.isoformat() if dt else None


def _hours(td: timedelta) -> float:
    return round(td.total_seconds() / 3600, 1)


def _rows(cur) -> List[Dict[str, Any]]:
    return [dict(r) for r in cur.fetchall()]


def _cursor(conn, engine):
    if engine == "postgresql":
        from psycopg2.extras import RealDictCursor
        return conn.cursor(cursor_factory=RealDictCursor)
    return conn.cursor()


