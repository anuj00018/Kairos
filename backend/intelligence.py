ACTION_TYPES = ("assign", "escalate", "set_status", "add_note", "reroute", "broadcast", "verify_resolution")


def _describe(a: Dict[str, Any], t: Optional[Dict]) -> str:
    tid = a.get("ticket_id")
    return {
        "assign": f"Assign {tid} to {a.get('owner')}" + (f" (currently {t['owner']})" if t else ""),
        "escalate": f"Escalate {tid} priority {t['priority'] if t else '?'} → {a.get('priority')}",
        "set_status": f"Change {tid} status {t['status'] if t else '?'} → {a.get('status')}",
        "add_note": f"Add operational note to {tid}: “{(a.get('note') or '')[:120]}”",
        "reroute": f"Re-route {tid} {t['department'] if t else '?'} → {a.get('department')}",
        "broadcast": f"Publish {a.get('level', 'warning')} broadcast to {a.get('sector', 'Campus-Wide')}: “{a.get('title')}”",
        "verify_resolution": f"Mark resolution of {tid} as verified",
    }.get(a.get("type"), "Unknown action")


def preview_actions(actions: List[Dict[str, Any]]) -> Dict[str, Any]:
    from .models import StatusEnum, VALID_STATUS_TRANSITIONS, PriorityEnum, DepartmentEnum
    snap = snapshot(force=True)
    by_id = {t["id"]: t for t in snap["tickets"]}
    staff = {n for n, _ in STAFF_DIRECTORY} | {"Unassigned"}
    items = []
    for a in actions[:25]:
        typ = a.get("type")
        t = by_id.get((a.get("ticket_id") or "").upper()) if a.get("ticket_id") else None
        problem = None
        if typ not in ACTION_TYPES:
            problem = "Unsupported action type."
        elif typ != "broadcast" and not t:
            problem = f"Ticket {a.get('ticket_id')} not found."
        elif typ == "assign" and a.get("owner") not in staff:
            problem = "Owner is not in the staff directory."
        elif typ == "escalate":
            try:
                PriorityEnum(a.get("priority"))
                if PRIORITY_RANK[a["priority"]] <= PRIORITY_RANK.get(t["priority"], 0):
                    problem = f"Already {t['priority']} — escalation would not raise priority."
            except ValueError:
                problem = "Invalid priority."
        elif typ == "set_status":
            try:
                if StatusEnum(a.get("status")) not in VALID_STATUS_TRANSITIONS.get(StatusEnum(t["status"]), set()):
                    problem = f"Transition {t['status']} → {a.get('status')} is not allowed."
            except ValueError:
                problem = "Invalid status."
        elif typ == "reroute":
            try:
                DepartmentEnum(a.get("department"))
            except ValueError:
                problem = "Invalid department."
        elif typ == "add_note" and not (a.get("note") or "").strip():
            problem = "Note is empty."
        elif typ == "broadcast" and not ((a.get("title") or "").strip() and (a.get("message") or "").strip()):
            problem = "Broadcast needs a title and message."
        elif typ == "verify_resolution" and t["status"] not in CLOSED:
            problem = f"{t['id']} is {t['status']} — only resolved incidents can be verified."
        items.append({"action": {**a, "ticket_id": t["id"] if t else a.get("ticket_id")},
                      "description": _describe(a, t), "valid": problem is None, "problem": problem})
    return {"items": items, "executable": sum(1 for i in items if i["valid"]),
            "requires_confirmation": True,
            "notice": "Nothing has been changed. Confirm to execute through the standard KAIROS workflow (audit-logged)."}


def execute_actions(actions: List[Dict[str, Any]], actor: str, reason: Optional[str], signal_key: Optional[str],
                    signal_fingerprint: Optional[str]) -> Dict[str, Any]:
    preview = preview_actions(actions)
    results = []
    reason_txt = f" Reason: {reason}" if reason else ""
    for item in preview["items"]:
        a = item["action"]
        if not item["valid"]:
            results.append({"description": item["description"], "ok": False, "error": item["problem"]})
            continue
        typ, tid = a["type"], a.get("ticket_id")
        ok = True
        if typ == "assign":
            ok = update_ticket_record(tid, {"owner": a["owner"], "comment": f"Assigned via Future Engine.{reason_txt}"}, actor=actor)
        elif typ == "escalate":
            ok = update_ticket_record(tid, {"priority": a["priority"], "comment": f"Escalated via Future Engine.{reason_txt}"}, actor=actor)
        elif typ == "set_status":
            ok = update_ticket_record(tid, {"status": a["status"]}, actor=actor)
            if ok and a["status"] in CLOSED:
                request_reverification(tid)
        elif typ == "add_note":
            ok = update_ticket_record(tid, {"comment": a["note"][:2000]}, actor=actor)
        elif typ == "reroute":
            ok = update_ticket_record(tid, {"department": a["department"], "comment": f"Re-routed via Future Engine.{reason_txt}"}, actor=actor)
        elif typ == "broadcast":
            create_broadcast_alert({"title": a["title"][:200], "message": a["message"][:2000], "level": a.get("level", "warning"),
                                    "sector": (a.get("sector") or "Campus-Wide")[:100]}, creator=actor)
        elif typ == "verify_resolution":
            record_verification(tid, "admin_verified", actor, a.get("note"), None)
        results.append({"description": item["description"], "ok": bool(ok), "error": None if ok else "Rejected by the ticket workflow."})
    invalidate()
    if signal_key and any(r["ok"] for r in results):
        set_signal_state(signal_key, "actioned", signal_fingerprint or "", actor, reason)
    return {"results": results, "executed": sum(1 for r in results if r["ok"]), "failed": sum(1 for r in results if not r["ok"])}
