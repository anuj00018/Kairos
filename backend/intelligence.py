# Snapshot: one consistent read of the operational data (3 queries, no N+1)
# ---------------------------------------------------------------------------

def _load() -> Dict[str, Any]:
    conn, engine = get_connection()
    cur = _cursor(conn, engine)
    cur.execute("""SELECT id, title, location, category, priority, department, status, owner, sla_hours,
                   created_at, resolved_at, summary, CASE WHEN image IS NULL OR image = '' THEN 0 ELSE 1 END AS has_image
                   FROM tickets""")
    tickets = _rows(cur)
    cur.execute("SELECT id, ticket_id, action, actor, created_at, notes FROM activity_logs ORDER BY id ASC")
    logs = _rows(cur)
    cur.execute("SELECT signal_key, state, fingerprint, actor, note, updated_at FROM signal_states")
    states = {r["signal_key"]: r for r in _rows(cur)}
    cur.execute("SELECT id, ticket_id, method, actor, note, reason, created_at, CASE WHEN image IS NULL OR image = '' THEN 0 ELSE 1 END AS has_image FROM resolution_verifications ORDER BY id ASC")
    verifications = _rows(cur)
    cur.execute("SELECT ticket_id FROM reporter_credentials")
    credentialed = {r["ticket_id"] for r in _rows(cur)}
    conn.close()

    logs_by_ticket: Dict[str, List[Dict]] = defaultdict(list)
    for l in logs:
        l["at"] = _parse(l["created_at"])
        logs_by_ticket[l["ticket_id"]].append(l)
    ver_by_ticket: Dict[str, List[Dict]] = defaultdict(list)
    for v in verifications:
        ver_by_ticket[v["ticket_id"]].append(v)

    out = []
    for t in tickets:
        created = _parse(t["created_at"]) or _now()
        tlogs = logs_by_ticket.get(t["id"], [])
        closed_at = _parse(t["resolved_at"])
        if t["status"] in CLOSED and not closed_at:
            # "Closed" clears resolved_at in the existing workflow — recover the time from the audit trail
            for l in reversed(tlogs):
                if l["action"].startswith("Status updated") and ("'Resolved'" in l["action"] or "'Closed'" in l["action"]):
                    closed_at = l["at"]
                    break
        assigned_at = next((l["at"] for l in tlogs if l["action"].startswith("Assigned owner to") and "'Unassigned'" not in l["action"]), None)
        building, mapped = resolve_building(t["location"])
        notes = [l for l in tlogs if l["action"].startswith("Note:")]
        out.append({
            **{k: t[k] for k in ("id", "title", "location", "category", "priority", "department", "status", "owner", "summary")},
            "sla_hours": int(t["sla_hours"] or 24),
            "created": created,
            "due": created + timedelta(hours=int(t["sla_hours"] or 24)),
            "closed_at": closed_at if t["status"] in CLOSED else None,
            "assigned_at": assigned_at,
            "last_activity": max([l["at"] for l in tlogs if l["at"]] or [created]),
            "building": building,
            "mapped": mapped,
            "service": CATEGORY_SERVICE.get(t["category"], "Facilities"),
            "has_image": bool(t["has_image"]),
            "notes": notes,
            "logs": tlogs,
            "verifications": ver_by_ticket.get(t["id"], []),
            "has_credential": t["id"] in credentialed,
        })
    return {"tickets": out, "states": states, "loaded_at": _now()}


def snapshot(force: bool = False) -> Dict[str, Any]:
    with _lock:
        if not force and _cache["snap"] and time.time() - _cache["at"] < CACHE_TTL:
            return _cache["snap"]
    snap = _load()
    with _lock:
        _cache.update(at=time.time(), snap=snap)
    return snap


def _is_open(t: Dict, at: datetime) -> bool:
    if t["created"] > at:
        return False
    if t["status"] in OPEN:
        return True
    return t["closed_at"] is not None and t["closed_at"] > at


def _is_breached(t: Dict, at: datetime) -> bool:
    return _is_open(t, at) and t["due"] < at


def _is_assigned(t: Dict, at: datetime) -> bool:
    if t["owner"] in (None, "", "Unassigned"):
        return False
    return t["assigned_at"] is None or t["assigned_at"] <= at


def _brief(t: Dict, now: Optional[datetime] = None) -> Dict[str, Any]:
    now = now or _now()
    remaining = t["due"] - now
    return {
        "id": t["id"], "title": t["title"], "location": t["location"], "building": t["building"],
        "category": t["category"], "priority": t["priority"], "department": t["department"],
        "status": t["status"], "owner": t["owner"], "created_at": _iso(t["created"]),
        "sla_due_at": _iso(t["due"]),
        "sla_remaining_hours": _hours(remaining) if t["status"] in OPEN else None,
        "is_breached": t["status"] in OPEN and remaining.total_seconds() < 0,
    }


