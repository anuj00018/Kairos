def _scenario_outcome(tickets: List[Dict], affected: List[Dict], now: datetime, horizon: timedelta,
                      extra_delay: timedelta = timedelta(0)) -> Dict[str, Any]:
    """Project SLA breaches and health at now+horizon if nothing is done vs. if affected work is actioned in time."""
    end = now + horizon
    would_breach = [t for t in affected if t["status"] in OPEN and t["due"] <= end + extra_delay and t["due"] > now]
    already = [t for t in affected if t["status"] in OPEN and t["due"] <= now]
    base = compute_health(tickets, now)
    no_action = compute_health(tickets, now, breach_overrides={t["id"] for t in would_breach + already})
    with_action = compute_health(tickets, now, resolved_overrides={t["id"] for t in would_breach})
    return {"would_breach": would_breach, "already_breached": already,
            "health_now": base["score"], "health_no_action": no_action["score"], "health_with_action": with_action["score"]}


def simulate(snap: Dict[str, Any], scenario: Dict[str, Any]) -> Dict[str, Any]:
    tickets, now = snap["tickets"], snap["loaded_at"]
    stype = scenario.get("type")
    hours = max(1, min(int(scenario.get("hours") or 24), 168))
    horizon = timedelta(hours=hours)
    label = "Scenario estimate based on available operational relationships"
    assumptions = [f"Campus topology: {TOPOLOGY_VERSION}.",
                   "'With preventive action' assumes the at-risk incidents are assigned and closed within their SLA.",
                   "Affected population is not estimated (occupancy not configured)."]

    if stype == "service_outage":
        building, service = scenario.get("building"), scenario.get("service")
        if building not in BUILDINGS or service not in SERVICE_LINES:
            raise ValueError("Choose a configured building and one of: " + ", ".join(SERVICE_LINES))
        scope = scenario.get("scope", "building")
        line = line_for(building, service)
        affected_b = buildings_on_line(service, line) if scope == "line" and line else [building]
        services = [service] + cascade(service)
        cats = {c for c, s in CATEGORY_SERVICE.items() if s in services} | {"Infrastructure"}
        affected = [t for t in tickets if t["building"] in affected_b and t["status"] in OPEN]
        related = [t for t in affected if t["category"] in cats]
        out = _scenario_outcome(tickets, related, now, horizon)
        out["blocked"] = [t["id"] for t in related]
        title = f"{service} loss at {building if scope == 'building' else line} for {hours}h"
        current = f"{len(affected)} open incidents in the affected area ({len(related)} related to {service.lower()} or dependent services)."
        impacts = [f"{b} ({BUILDINGS[b]['type']}): {BUILDING_IMPACT[BUILDINGS[b]['type']]}" for b in affected_b]
        dependencies = [f"{service} → {d}" for d in cascade(service)] + ([f"{building} is on {line}"] if line else [])
        response = [
            f"Notify occupants of {', '.join(affected_b)} via campus broadcast",
            f"Dispatch {'Electrical Maintenance' if service == 'Power' else 'Facilities' if service == 'Water' else 'IT Infrastructure'} to the affected {'line' if scope == 'line' else 'building'}",
            f"Prioritise {len(out['would_breach'])} incident(s) whose SLA falls inside the outage window" if out["would_breach"] else "No open SLA deadlines fall inside the outage window",
        ]
        if "Lifts" in services:
            response.append("Check lifts for trapped occupants and enable manual override")
        if "Pumped Water" in services:
            response.append("Arrange temporary water supply for upper floors (pumped supply stops)")
    elif stype == "delay_ticket":
        tid = (scenario.get("ticket_id") or "").upper()
        t = next((x for x in tickets if x["id"] == tid), None)
        if not t:
            raise ValueError(f"Ticket {tid} not found.")
        if t["status"] not in OPEN:
            raise ValueError(f"{tid} is already {t['status']} — nothing to delay.")
        same = [x for x in tickets if x["building"] == t["building"] and x["category"] == t["category"] and x["status"] in OPEN]
        remaining = t["due"] - now
        breaches = remaining < horizon
        out = _scenario_outcome(tickets, [t], now, horizon)
        if breaches and t not in out["would_breach"] and t not in out["already_breached"]:
            out["would_breach"].append(t)
        affected_b = [t["building"]]
        services = [t["service"]] + cascade(t["service"])
        title = f"Delay {tid} by {hours}h"
        current = f"{tid} ({t['priority']}, {t['status']}) has {_hours(remaining)}h of SLA remaining; {len(same) - 1} other open {t['category'].lower()} report(s) in {t['building']}."
        impacts = [f"{tid} {'would breach its SLA' if breaches else 'would still be inside its SLA'} after a {hours}h delay"]
        if len(same) > 1:
            impacts.append(f"{len(same) - 1} related open report(s) in the same building remain exposed to the same cause")
        dependencies = [f"{t['service']} → {d}" for d in cascade(t["service"])]
        response = ([f"Do not delay — assign now; {_hours(remaining)}h of SLA remain"] if breaches else
                    [f"Delay is possible within SLA ({_hours(remaining - horizon)}h buffer would remain)"])
    elif stype == "ignore_signal":
        signals = detect_signals(snap)
        sig = next((s for s in signals if s["id"] == scenario.get("signal_id")), None)
        if not sig:
            raise ValueError("That risk signal is no longer active.")
        group = [t for t in tickets if t["id"] in sig["open_ticket_ids"]]
        out = _scenario_outcome(tickets, group, now, horizon)
        affected_b = sorted({t["building"] for t in group})
        services = [sig["service"]] + cascade(sig["service"]) if sig["service"] in SERVICE_LINES else [sig["service"]]
        title = f"Do nothing about “{sig['title']}” for {hours}h"
        current = f"{len(group)} open linked incident(s); risk {sig['level']} ({sig['score']}/100)."
        impacts = [sig["potential_impact"]["summary"]]
        if sig["recurrence"]:
            impacts.append(f"{len(sig['recurrence'])} report(s) already recurred within 7 days of a fix — repeat reports are likely to continue")
        dependencies = [f"{sig['service']} → {d}" for d in cascade(sig["service"])]
        if sig.get("line"):
            dependencies.append(f"Buildings on {sig['line']}: {', '.join(buildings_on_line(sig['service'], sig['line']))}")
        response = [r["title"] for r in sig["recommendations"] if r["actions"]]
    else:
        raise ValueError("Unknown scenario type. Use service_outage, delay_ticket or ignore_signal.")

    history = [t for t in tickets if t["building"] in affected_b and t["closed_at"]]
    return {
        "title": title, "label": label, "horizon_hours": hours, "generated_at": now.isoformat(),
        "current_state": current,
        "affected_buildings": affected_b, "affected_services": services,
        "potential_impact": impacts, "dependencies": dependencies, "recommended_response": response,
        "no_action": {
            "sla_breaches": len(out["would_breach"]) + len(out["already_breached"]),
            "new_breaches": [x["id"] for x in out["would_breach"]],
            "health": out["health_no_action"],
            "summary": f"{len(out['would_breach'])} additional SLA breach(es) within {hours}h; campus health {out['health_now']} → {out['health_no_action']}."
                       + (f" {len(out['blocked'])} open related incident(s) cannot be worked during the disruption." if out.get("blocked") else ""),
            "blocked_incidents": out.get("blocked", []),
        },
        "with_action": {
            "sla_breaches": len(out["already_breached"]),
            "breaches_avoided": len(out["would_breach"]),
            "health": out["health_with_action"],
            "summary": f"{len(out['would_breach'])} breach(es) avoided if actioned now; campus health {out['health_now']} → {out['health_with_action']}.",
        },
        "health_now": out["health_now"],
        "historical_precedents": len(history),
        "assumptions": assumptions,
    }


