def issue_reporter_token(ticket_id: str) -> str:
    """Secret handed to the submitter once; only its SHA-256 is stored."""
    token = secrets.token_urlsafe(24)
    conn, engine = get_connection()
    cur = conn.cursor()
    ph = "%s" if engine == "postgresql" else "?"
    cur.execute(f"DELETE FROM reporter_credentials WHERE ticket_id = {ph}", (ticket_id,))
    cur.execute(f"INSERT INTO reporter_credentials (ticket_id, token_hash, created_at) VALUES ({ph},{ph},{ph})",
                (ticket_id, hashlib.sha256(token.encode()).hexdigest(), _now().isoformat()))
    conn.commit()
    conn.close()
    return token


def check_reporter_token(ticket_id: str, token: Optional[str]) -> bool:
    if not token or len(token) > 100:
        return False
    conn, engine = get_connection()
    cur = conn.cursor()
    ph = "%s" if engine == "postgresql" else "?"
    cur.execute(f"SELECT token_hash FROM reporter_credentials WHERE ticket_id = {ph}", (ticket_id,))
    row = cur.fetchone()
    conn.close()
    if not row:
        return False
    stored = row["token_hash"] if isinstance(row, dict) else row[0]
    return hmac.compare_digest(stored, hashlib.sha256(token.encode()).hexdigest())


def _status_events(t: Dict) -> List[Dict[str, Any]]:
    out = []
    for l in t["logs"]:
        if l["action"].startswith("Status updated from"):
            try:
                frm = l["action"].split("'")[1]
                to = l["action"].split("'")[3]
            except IndexError:
                continue
            out.append({"from": frm, "to": to, "at": l["at"], "actor": l["actor"]})
    return out


def _resolution_times(t: Dict) -> List[datetime]:
    """Moments the ticket moved from open work into Resolved/Closed (each starts a verification cycle)."""
    times = [e["at"] for e in _status_events(t) if e["to"] in CLOSED and e["from"] not in CLOSED and e["at"]]
    if not times and t["closed_at"]:
        times = [t["closed_at"]]
    return times


def _public_actor(actor: str) -> str:
    if actor.startswith("Admin") or "Future Engine" in actor:
        return "Operations team"
    if actor in ("KAIROS Triage", "KAIROS", "KAIROS Reverification"):
        return "KAIROS"
    return actor


def _lifecycle(t: Dict, include_private: bool) -> List[Dict[str, Any]]:
    events: List[Dict[str, Any]] = []
    seen_assign = False
    for l in t["logs"]:
        a, at = l["action"], _iso(l["at"])
        actor = l["actor"] if include_private else _public_actor(l["actor"])
        if a.startswith("Complaint submitted"):
            events.append({"stage": "Report created", "kind": "report", "at": at, "actor": actor})
        elif "classified as" in a:
            events.append({"stage": "AI triaged", "kind": "triage", "at": at, "actor": actor, "detail": a.replace("KAIROS classified as ", "")})
        elif a.startswith("Assigned owner to") and "'Unassigned'" not in a and not seen_assign:
            seen_assign = True
            events.append({"stage": "Assigned", "kind": "assign", "at": at, "actor": actor, "detail": a.split("'")[1] if include_private or True else None})
        elif a.startswith("Status updated from"):
            parts = a.split("'")
            frm, to = (parts[1], parts[3]) if len(parts) > 3 else ("", "")
            if to == "In Progress" and frm not in CLOSED:
                events.append({"stage": "Work started", "kind": "work", "at": at, "actor": actor})
            elif to in CLOSED and frm not in CLOSED:
                events.append({"stage": "Marked resolved", "kind": "resolved", "at": at, "actor": actor})
            elif frm in CLOSED and to not in CLOSED:
                events.append({"stage": "Reopened for review", "kind": "reopened", "at": at, "actor": actor})
        elif a.startswith("Reporter reverification requested"):
            events.append({"stage": "Reverification requested", "kind": "requested", "at": at, "actor": "KAIROS"})
    for v in t["verifications"]:
        label = {"reporter_confirmed": "Reporter verified", "reporter_disputed": "Reporter disputed",
                 "admin_verified": "Administrator verified"}.get(v["method"], v["method"])
        ev = {"stage": label, "kind": v["method"], "at": v["created_at"],
              "actor": "Reporter" if v["method"].startswith("reporter") else ("Operations team" if not include_private else v["actor"])}
        if v["method"] == "reporter_disputed":
            ev["detail"] = DISPUTE_REASONS.get(v.get("reason") or "", "Problem still exists")
        events.append(ev)
    events.sort(key=lambda e: e["at"] or "")
    return events


def verification_for(t: Dict, tickets: List[Dict], now: datetime, include_private: bool = False,
                     has_credential: Optional[bool] = None, admin_view: bool = False) -> Dict[str, Any]:
    has_credential = t.get("has_credential", False) if has_credential is None else has_credential
    res_times = _resolution_times(t)
    last_res = res_times[-1] if res_times else None
    cycle = [v for v in t["verifications"] if last_res and (_parse(v["created_at"]) or now) >= last_res]
    reporter_cycle = [v for v in cycle if v["method"].startswith("reporter")]
    disputes = [v for v in t["verifications"] if v["method"] == "reporter_disputed"]
    reopen_count = sum(1 for e in _status_events(t) if e["from"] in CLOSED and e["to"] not in CLOSED)
    last_dispute = disputes[-1] if disputes else None
    is_closed = t["status"] in CLOSED

    if not is_closed:
        if last_dispute and last_res and (_parse(last_dispute["created_at"]) or now) >= last_res:
            status, state = "Disputed", "disputed_returned"
        else:
            status, state = "Open", "open"
    elif any(v["method"] == "reporter_confirmed" for v in reporter_cycle):
        status, state = "Verified", "verified_reporter"
    elif any(v["method"] == "reporter_disputed" for v in reporter_cycle):
        status, state = "Disputed", "disputed"
    elif any(v["method"] == "admin_verified" for v in cycle):
        status, state = "Verified", "verified_admin"
    elif has_credential:
        status, state = "Awaiting reverification", "awaiting_reporter"
    else:
        status, state = "Resolved — awaiting verification", "awaiting_admin"

    evidence = []
    if last_res:
        evidence.append({"type": "timestamp", "label": f"Marked resolved {last_res.strftime('%Y-%m-%d %H:%M')} UTC"})
    if t["owner"] not in (None, "", "Unassigned"):
        evidence.append({"type": "assignment", "label": f"Handled by {t['owner']} ({t['department']})"})
    tech_notes = [n for n in t["notes"] if t["assigned_at"] is None or (n["at"] and n["at"] >= t["assigned_at"])]
    if tech_notes:
        evidence.append({"type": "technician_update", "label": f"Technician/admin update: “{tech_notes[-1]['action'][6:][:140]}”"})
    if t["has_image"]:
        evidence.append({"type": "intake_photo", "label": "Photo on file from the original report (intake evidence, not proof of fix)"})
    evidence.append({"type": "location", "label": f"Location: {t['location']}"})

    # Possible recurrence: a similar report after this resolution. Evidence only — not proof the fix failed.
    recurrence = []
    if last_res:
        verified_at = next((_parse(v["created_at"]) for v in cycle if v["method"] in ("reporter_confirmed", "admin_verified")), None)
        anchor = verified_at or last_res
        follow = [x for x in tickets if x["id"] != t["id"] and x["building"] == t["building"] and x["category"] == t["category"]
                  and anchor < x["created"] <= anchor + RECURRENCE_WINDOW]
        for f in follow:
            days = max(0.1, (f["created"] - anchor).total_seconds() / 86400)
            recurrence.append({"ticket_id": f["id"], "title": f["title"], "reported_at": _iso(f["created"]),
                               "after": "verification" if verified_at else "resolution",
                               "label": f"Possible recurrence detected: {f['id']} ({t['category'].lower()}, {t['building']}) reported "
                                        f"{days:.1f} day(s) after {'verification' if verified_at else 'resolution'}"})
        if recurrence:
            evidence += [{"type": "possible_recurrence", "label": r["label"], "negative": True} for r in recurrence]
        elif (now - anchor) >= timedelta(hours=24):
            evidence.append({"type": "no_recurrence", "label": f"No similar report in the {min(7, (now - anchor).days or 1)} day(s) since {'verification' if verified_at else 'resolution'}"})

    for v in cycle:
        label = {"admin_verified": "Administrator verification (does not replace reporter confirmation)",
                 "reporter_confirmed": "Reporter confirmed the fix",
                 "reporter_disputed": f"Reporter disputed: {DISPUTE_REASONS.get(v.get('reason') or '', 'problem still exists')}"}.get(v["method"], v["method"])
        if include_private and v.get("note"):
            label += f" — “{v['note']}”"
        if v.get("has_image"):
            label += " (photo attached)"
        evidence.append({"type": v["method"], "label": label, "at": v["created_at"], "negative": v["method"] == "reporter_disputed"})

    decisive = next((v for v in reversed(reporter_cycle)), None) or next((v for v in reversed(cycle)), None)
    dispute_info = None
    if last_dispute:
        dispute_info = {"reason": last_dispute.get("reason"), "reason_label": DISPUTE_REASONS.get(last_dispute.get("reason") or "", "Problem still exists"),
                        "at": last_dispute["created_at"], "has_image": bool(last_dispute.get("has_image")), "verification_id": last_dispute["id"],
                        "note": last_dispute.get("note") if include_private else None}

    lifecycle = _lifecycle(t, admin_view)  # staff identities only for administrators
    if state == "awaiting_reporter":
        lifecycle.append({"stage": "Awaiting reverification", "kind": "pending", "at": None, "actor": "Reporter"})

    return {
        "status": status, "state": state,
        "reporter_can_respond": is_closed and has_credential and not reporter_cycle,
        "evidence": evidence,
        "method": {"admin_verified": "Administrator verification", "reporter_confirmed": "Reporter confirmation",
                   "reporter_disputed": "Reporter dispute"}.get(decisive["method"]) if decisive else None,
        "verified_at": decisive["created_at"] if decisive else None,
        "resolved_at": _iso(last_res),
        "resolved_by": {"team": t["department"], "owner": t["owner"] if t["owner"] not in (None, "", "Unassigned") else None},
        "reopen_count": reopen_count, "dispute_count": len(disputes),
        "last_dispute": dispute_info,
        "possible_recurrence": recurrence,
        "policy": verification_policy(t),
        "lifecycle": lifecycle,
    }


def ticket_verification(ticket_id: str, include_private: bool = False, admin_view: bool = False) -> Optional[Dict[str, Any]]:
    snap = snapshot(force=True)
    t = next((x for x in snap["tickets"] if x["id"] == ticket_id), None)
    if not t:
        return None
    out = {"ticket_id": ticket_id, "title": t["title"], "ticket_status": t["status"],
           **verification_for(t, snap["tickets"], snap["loaded_at"], include_private, admin_view=admin_view)}
    if include_private and out["last_dispute"] and out["last_dispute"]["has_image"]:
        conn, engine = get_connection()
        cur = conn.cursor()
        ph = "%s" if engine == "postgresql" else "?"
        cur.execute(f"SELECT image FROM resolution_verifications WHERE id = {ph}", (out["last_dispute"]["verification_id"],))
        row = cur.fetchone()
        conn.close()
        out["last_dispute"]["image"] = (row["image"] if isinstance(row, dict) else row[0]) if row else None
    return out


def record_verification(ticket_id: str, method: str, actor: str, note: Optional[str], image: Optional[str],
                        reason: Optional[str] = None) -> None:
    conn, engine = get_connection()
    cur = conn.cursor()
    ph = "%s" if engine == "postgresql" else "?"
    now = _now().isoformat()
    cur.execute(f"INSERT INTO resolution_verifications (ticket_id, method, actor, note, image, created_at, reason) VALUES ({ph},{ph},{ph},{ph},{ph},{ph},{ph})",
                (ticket_id, method, actor, note, image, now, reason))
    action = {"admin_verified": "Resolution verified by administrator",
              "reporter_confirmed": "Reporter confirmed resolution",
              "reporter_disputed": f"Reporter disputed resolution: {DISPUTE_REASONS.get(reason or '', 'problem still exists')}"}[method]
    cur.execute(f"INSERT INTO activity_logs (ticket_id, action, actor, created_at, notes) VALUES ({ph},{ph},{ph},{ph},{ph})",
                (ticket_id, action, actor, now, note))
    conn.commit()
    conn.close()
    invalidate()


class ReverificationError(Exception):
    def __init__(self, status: int, message: str):
        super().__init__(message)
        self.status = status


def reporter_respond(ticket_id: str, token: Optional[str], confirmed: bool, reason: Optional[str],
                     note: Optional[str], image: Optional[str]) -> Dict[str, Any]:
    """Server-authoritative reporter decision. One response per resolution cycle."""
    if not check_reporter_token(ticket_id, token):
        raise ReverificationError(403, "Only the person who reported this ticket can verify its resolution on this device.")
    snap = snapshot(force=True)
    t = next((x for x in snap["tickets"] if x["id"] == ticket_id), None)
    if not t:
        raise ReverificationError(404, f"Ticket {ticket_id} not found")
    if t["status"] not in CLOSED:
        raise ReverificationError(400, "This ticket is not marked resolved, so there is nothing to verify yet.")
    v = verification_for(t, snap["tickets"], snap["loaded_at"], has_credential=True)
    if not v["reporter_can_respond"]:
        raise ReverificationError(409, "You have already responded to this resolution.")
    if sum(1 for x in t["verifications"] if x["method"].startswith("reporter")) >= MAX_REPORTER_RESPONSES:
        raise ReverificationError(429, "This ticket has reached the maximum number of reverification responses. Operations will follow up directly.")
    if not confirmed and reason not in DISPUTE_REASONS:
        raise ReverificationError(400, "Please choose what is still wrong.")

    if confirmed:
        record_verification(ticket_id, "reporter_confirmed", "Reporter", note, None)
    else:
        record_verification(ticket_id, "reporter_disputed", "Reporter", note, image, reason)
        # Return to the existing operational workflow — visibly, with a reason, never silently.
        update_ticket_record(ticket_id, {"status": "In Progress",
                                         "comment": f"Returned for review after reporter dispute ({DISPUTE_REASONS[reason]})."},
                             actor="KAIROS Reverification")
    invalidate()
    return ticket_verification(ticket_id, include_private=True)


def request_reverification(ticket_id: str) -> bool:
    """Called after a ticket enters Resolved/Closed. Logs the request once per cycle when a reporter can respond."""
    snap = snapshot(force=True)
    t = next((x for x in snap["tickets"] if x["id"] == ticket_id), None)
    if not t or t["status"] not in CLOSED or not t.get("has_credential"):
        return False
    last_res = (_resolution_times(t) or [None])[-1]
    if last_res and any(l["action"].startswith("Reporter reverification requested") and l["at"] and l["at"] >= last_res for l in t["logs"]):
        return False
    conn, engine = get_connection()
    cur = conn.cursor()
    ph = "%s" if engine == "postgresql" else "?"
    cur.execute(f"INSERT INTO activity_logs (ticket_id, action, actor, created_at) VALUES ({ph},{ph},{ph},{ph})",
                (ticket_id, "Reporter reverification requested (in-app)", "KAIROS", _now().isoformat()))
    conn.commit()
    conn.close()
    invalidate()
    return True


def reporter_tickets(pairs: List[Dict[str, str]]) -> List[Dict[str, Any]]:
    """Status of the tickets this device reported. Pairs with a wrong token are silently skipped."""
    snap = snapshot()
    by_id = {t["id"]: t for t in snap["tickets"]}
    out = []
    for p in pairs[:50]:
        tid = (p.get("ticket_id") or "").upper()[:30]
        t = by_id.get(tid)
        if not t or not check_reporter_token(tid, p.get("token")):
            continue
        v = verification_for(t, snap["tickets"], snap["loaded_at"], include_private=True, has_credential=True)
        out.append({"ticket_id": tid, "title": t["title"], "location": t["location"], "status": t["status"],
                    "verification_status": v["status"], "state": v["state"], "reporter_can_respond": v["reporter_can_respond"],
                    "resolved_at": v["resolved_at"], "resolved_by": v["resolved_by"], "policy": v["policy"],
                    "last_dispute": v["last_dispute"], "verified_at": v["verified_at"]})
    return out


def _memory_verification(t: Dict, tickets: List[Dict], now: datetime) -> Dict[str, Any]:
    v = verification_for(t, tickets, now)
    confirmed = next((x for x in t["verifications"] if x["method"] == "reporter_confirmed"), None)
    return {"verification": v["status"], "verified_at": v["verified_at"],
            "reporter_confirmed": bool(confirmed), "reopen_count": v["reopen_count"],
            "dispute_reason": v["last_dispute"]["reason_label"] if v["last_dispute"] else None,
            "possible_recurrence": [r["ticket_id"] for r in v["possible_recurrence"]]}


def campus_memory(snap: Dict[str, Any], ticket_id: Optional[str] = None, building: Optional[str] = None,
                  category: Optional[str] = None, query: Optional[str] = None) -> Dict[str, Any]:
    tickets, now = snap["tickets"], snap["loaded_at"]
    anchor = None
    if ticket_id:
        anchor = next((t for t in tickets if t["id"] == ticket_id.upper()), None)
        if not anchor:
            return {"found": False, "message": f"Ticket {ticket_id.upper()} not found.", "incidents": []}
        building, category = anchor["building"], anchor["category"]
    if building:
        building = resolve_building(building)[0]
    q = (query or "").lower().strip()

    def match(t):
        if anchor and t["id"] == anchor["id"]:
            return False
        if building and t["building"] != building:
            return False
        if category and t["category"].lower() != category.lower():
            return False
        if q and q not in f"{t['title']} {t['location']} {t['summary']}".lower():
            return False
        return t["status"] in CLOSED

    past = sorted([t for t in tickets if match(t)], key=lambda t: t["created"], reverse=True)
    items = []
    for t in past[:25]:
        resolution = t["notes"][-1]["action"][6:] if t["notes"] else None
        items.append({
            "id": t["id"], "title": t["title"], "date": _iso(t["created"]), "location": t["location"],
            "building": t["building"], "category": t["category"], "department": t["department"],
            "owner": t["owner"], "resolution": resolution or "No resolution note recorded",
            "duration_hours": _hours(t["closed_at"] - t["created"]) if t["closed_at"] else None,
            "within_sla": (t["closed_at"] <= t["due"]) if t["closed_at"] else None,
            **_memory_verification(t, tickets, now),
        })
    durations = [i["duration_hours"] for i in items if i["duration_hours"] is not None]
    scope = " · ".join(x for x in [building, category, f"“{query}”" if query else None] if x) or "all locations"
    if len(items) == 0:
        return {"found": False, "scope": scope, "incidents": [], "message": "Not enough historical data — no resolved incidents match this scope."}
    return {
        "found": True, "scope": scope, "incidents": items, "count": len(past),
        "summary": {
            "count": len(past),
            "median_resolution_hours": sorted(durations)[len(durations) // 2] if durations else None,
            "within_sla": sum(1 for i in items if i["within_sla"]),
            "reporter_verified": sum(1 for i in items if i["reporter_confirmed"]),
            "reopened": sum(i["reopen_count"] for i in items),
            "departments": dict(Counter(i["department"] for i in items)),
            "first_seen": items[-1]["date"], "last_seen": items[0]["date"],
        },
        "message": None if len(past) >= 3 else "Limited history — fewer than 3 resolved incidents match; treat patterns with caution.",
    }


