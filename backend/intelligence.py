def incident_graph(snap: Dict[str, Any], signal_id: Optional[str] = None, signals: Optional[List[Dict]] = None) -> Dict[str, Any]:
    signals = signals if signals is not None else detect_signals(snap)
    chosen = [s for s in signals if s["id"] == signal_id] if signal_id else signals[:4]
    nodes: Dict[str, Dict] = {}
    edges: List[Dict] = []
    by_id = {t["id"]: t for t in snap["tickets"]}

    def node(nid, ntype, label, **extra):
        nodes.setdefault(nid, {"id": nid, "type": ntype, "label": label, **extra})

    for s in chosen:
        sid = f"pattern:{s['id']}"
        node(sid, "pattern", s["title"], level=s["level"], score=s["score"])
        for tid in s["ticket_ids"]:
            t = by_id.get(tid)
            if not t:
                continue
            node(f"ticket:{tid}", "incident", tid, title=t["title"], priority=t["priority"], status=t["status"])
            node(f"building:{t['building']}", "building", t["building"])
            node(f"service:{t['service']}", "service", t["service"])
            edges.append({"from": f"ticket:{tid}", "to": f"building:{t['building']}", "rel": "located in"})
            edges.append({"from": f"ticket:{tid}", "to": f"service:{t['service']}", "rel": "affects"})
            edges.append({"from": f"ticket:{tid}", "to": sid, "rel": "signal of"})
            line = line_for(t["building"], t["service"])
            if line:
                node(f"line:{line}", "line", line)
                edges.append({"from": f"building:{t['building']}", "to": f"line:{line}", "rel": "supplied by"})
                edges.append({"from": f"line:{line}", "to": f"service:{t['service']}", "rel": "carries"})
            else:
                edges.append({"from": f"building:{t['building']}", "to": f"service:{t['service']}", "rel": "uses"})
            edges.append({"from": f"service:{t['service']}", "to": sid, "rel": "pattern in"})
        edges.append({"from": sid, "to": f"cause:{s['id']}", "rel": "possible common cause"})
        node(f"cause:{s['id']}", "cause", f"Possible common cause: {s['line'] or s['building'] or s['where']}")
    unique = list({(e["from"], e["to"]): e for e in edges}.values())
    return {"nodes": list(nodes.values()), "edges": unique,
            "note": "Relationships come from ticket data (location, category, timing) and the configured campus topology."}


